"""Generate the dependency page of a detailed design from the Bazel dependency graph.

The page lists, per unit, the direct dependencies and their FFI tag, and the
external repositories reachable transitively. ``bazel query`` evaluates all
``select()`` branches.

Usage:
    python3 scripts/generate_dependency_report.py CONFIG...           # write the pages
    python3 scripts/generate_dependency_report.py CONFIG... --check   # fail if outdated

CONFIG is a JSON file, see scripts/dependency_reports/ for examples:
    output       page path, relative to the repository root
    title        page title
    document_id  need id of the page
    safety       safety level of the page (``QM`` or ``ASIL_B``)
    security     security attribute of the page (``YES`` or ``NO``)
    component    Bazel pattern of the component, its targets are not external
    units        list of {"name": ..., "scope": ...}, ``scope`` is a Bazel pattern
    realizes     optional, work product of the page (default ``wp__sw_implementation``)
"""

import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

BAZEL_INFRASTRUCTURE_REPOS = {"", "bazel_tools", "platforms", "rules_cc"}
MISSING_PACKAGES = set()

HEADER = """\
..
   # *******************************************************************************
   # Copyright (c) 2026 Contributors to the Eclipse Foundation
   #
   # See the NOTICE file(s) distributed with this work for additional
   # information regarding copyright ownership.
   #
   # This program and the accompanying materials are made available under the
   # terms of the Apache License Version 2.0 which is available at
   # https://www.apache.org/licenses/LICENSE-2.0
   #
   # SPDX-License-Identifier: Apache-2.0
   # *******************************************************************************

.. Generated by scripts/generate_dependency_report.py. Do not edit.

.. document:: {title}
   :id: {document_id}
   :status: draft
   :version: 1
   :safety: {safety}
   :security: {security}
   :realizes: {realizes}

{title}
{underline}

The tables are generated from the Bazel dependency graph with
``scripts/generate_dependency_report.py``. The query evaluates all ``select()``
branches, so platform specific dependencies (for example QNX) are included.

The column ``FFI`` shows if the target carries the ``FFI`` tag, which marks
libraries that are used under freedom from interference requirements.

Regenerate the page after a change of a dependency with
``python3 scripts/generate_dependency_report.py {config}``. With ``--check`` the
script fails if the page is outdated.
"""


def bazel_query(expression, output):
    result = subprocess.run(
        [
            "bazel",
            "query",
            expression,
            f"--output={output}",
            "--noshow_progress",
            "--keep_going",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    # Exit code 3: the query is partial because of errors, which are reported on the page.
    if result.returncode not in (0, 3):
        sys.exit(f"bazel query failed for '{expression}':\n{result.stderr}")
    for match in re.finditer(r"no such package '([^']+)'", result.stderr):
        MISSING_PACKAGES.add(match.group(1))
    return result.stdout


def query_rules(expression):
    """Return {label: (rule class, FFI tag set, alias target or None)}."""
    rules = {}
    root = ET.fromstring(bazel_query(expression, "xml"))
    for rule in root.iter("rule"):
        tags = {
            s.get("value")
            for lst in rule.findall("list[@name='tags']")
            for s in lst.findall("string")
        }
        actual = rule.find("label[@name='actual']")
        rules[rule.get("name")] = (
            rule.get("class"),
            "FFI" in tags,
            actual.get("value") if actual is not None else None,
        )
    return rules


def resolve_aliases(rules):
    """Take the FFI tag of the aliased target if the alias itself has none."""
    actuals = sorted({actual for _, _, actual in rules.values() if actual})
    targets = query_rules(" + ".join(actuals)) if actuals else {}
    resolved = {}
    for label, (kind, ffi, actual) in rules.items():
        if actual and not ffi and actual in targets:
            ffi = targets[actual][1]
        resolved[label] = (kind, ffi)
    return resolved


def repo_name(label):
    repo = label.split("//", 1)[0].lstrip("@")
    if "_repo_rules+" in repo:
        repo = repo.split("_repo_rules+", 1)[1]
    repo = repo.rstrip("+")
    return "boost" if repo.startswith("boost.") else repo


def yes_no(flag):
    return "yes" if flag else "no"


def table(header, rows, widths):
    lines = [".. list-table::", "   :header-rows: 1", f"   :widths: {widths}", ""]
    for cells in [header] + rows:
        for position, cell in enumerate(cells):
            prefix = "   * - " if position == 0 else "     - "
            lines.append(f"{prefix}{cell}")
    return "\n".join(lines) + "\n"


def unit_section(name, scope, component):
    libraries = f'kind(".*_library", {scope}) except attr(testonly, 1, {scope})'
    own = query_rules(libraries)
    own_rows = [
        [f"``{label}``", yes_no(ffi)] for label, (_, ffi, _) in sorted(own.items())
    ]

    direct = resolve_aliases(
        query_rules(f"labels(deps, {libraries}) except ({libraries})")
    )
    direct_rows = [
        [f"``{label}``", kind, yes_no(ffi)]
        for label, (kind, ffi) in sorted(direct.items())
    ]

    transitive = bazel_query(f"deps({libraries}) except {component}", "label").split()
    repos = {repo_name(label) for label in transitive} - BAZEL_INFRASTRUCTURE_REPOS

    section = (
        f"{name}\n{'=' * len(name)}\n\nTargets of the unit\n-------------------\n\n"
    )
    section += table(["Target", "FFI"], own_rows, "80 20") + "\n"
    section += "Direct dependencies\n-------------------\n\n"
    section += table(["Target", "Kind", "FFI"], direct_rows, "70 15 15")
    return section, repos


def generate(config, config_path):
    MISSING_PACKAGES.clear()
    sections = []
    repo_users = {}
    for unit in config["units"]:
        section, repos = unit_section(unit["name"], unit["scope"], config["component"])
        sections.append(section)
        for repo in repos:
            repo_users.setdefault(repo, []).append(unit["name"])

    repo_rows = [
        [f"``{repo}``", ", ".join(users)] for repo, users in sorted(repo_users.items())
    ]
    transitive = "External Repositories\n=====================\n\n"
    transitive += (
        "Repositories reachable transitively from the targets of each unit.\n\n"
    )
    transitive += table(["Repository", "Used by"], repo_rows, "30 70")

    unresolved = "Unresolved Dependencies\n=======================\n\n"
    if MISSING_PACKAGES:
        unresolved += (
            "Targets depend on packages that do not exist. The query continues without\n"
            "them, so their dependencies are missing from the tables above.\n\n"
        )
        unresolved += table(
            ["Missing package"], [[f"``{p}``"] for p in sorted(MISSING_PACKAGES)], "100"
        )
    else:
        unresolved += "All dependencies are resolved.\n"

    header = HEADER.format(
        title=config["title"],
        underline="#" * len(config["title"]),
        document_id=config["document_id"],
        safety=config["safety"],
        security=config["security"],
        realizes=config.get("realizes", "wp__sw_implementation"),
        config=config_path,
    )
    return header + "\n" + "\n".join(sections) + "\n" + transitive + "\n" + unresolved


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "configs", nargs="+", type=Path, help="JSON configuration of a page"
    )
    parser.add_argument(
        "--check", action="store_true", help="fail if a page is outdated"
    )
    args = parser.parse_args()

    failed = []
    for config_file in args.configs:
        config_path = config_file.resolve().relative_to(ROOT).as_posix()
        config = json.loads(config_file.read_text())
        content = generate(config, config_path)
        output = ROOT / config["output"]
        if not args.check:
            output.write_text(content)
        elif not output.exists() or output.read_text() != content:
            failed.append(config["output"])
    if failed:
        sys.exit(
            f"outdated: {', '.join(failed)}, run scripts/generate_dependency_report.py <config>"
        )


if __name__ == "__main__":
    main()
